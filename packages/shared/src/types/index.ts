/** Priority level for a task. */
export enum Priority {
  Low = "low",
  Medium = "medium",
  High = "high",
  Critical = "critical",
}

/** Type of blocked time slot. */
export enum BlockType {
  SingleDay = "single-day",
  RecurringWeekday = "recurring-weekday",
  RecurringPeriod = "recurring-period",
}

/** Calendar view mode. */
export enum ViewType {
  Day = "day",
  Week = "week",
  Month = "month",
}

/** Completion status of a scheduled event. */
export enum CompletionStatus {
  Pending = "pending",
  Completed = "completed",
  Skipped = "skipped",
}

/** Named time group preset. */
export type TimeGroupPreset = "morning" | "afternoon" | "evening" | "night";

/** Custom hour range (0–23). */
export interface CustomRange {
  /** Start hour (0–23). */
  startHour: number;
  /** End hour (0–23). */
  endHour: number;
}

/** A restricted time range — either a named preset or a custom range. */
export type RestrictedRange =
  | { preset: TimeGroupPreset }
  | { custom: CustomRange };

/** Restriction applied to a task's scheduling window. */
export type TaskRestriction =
  | { type: "morning-only" }
  | { type: "afternoon-only" }
  | { type: "no-weekends" }
  | { type: "weekdays-only" }
  | { type: "specific-days"; days: number[] }
  | { type: "restricted-range"; ranges: RestrictedRange[] };

/** A user-defined recurring task. */
export interface Task {
  /** Unique identifier. */
  id: string;
  /** Display title. */
  title: string;
  /** Optional description. */
  description?: string;
  /** Duration in minutes (must be a multiple of 30). */
  duration: number;
  /** Scheduling priority. */
  priority: Priority;
  /** Scheduling restrictions. */
  restrictions: TaskRestriction[];
  /** Whether the task is active. */
  isActive: boolean;
  /** How many times per week (default: 1). */
  frequency?: number;
  /** Minimum days between occurrences (default: 1). */
  gapDays?: number;
  /** Allow multiple occurrences on the same day (default: false). */
  allowSameDay?: boolean;
  /** ISO-8601 creation timestamp. */
  createdAt: string;
  /** ISO-8601 last-update timestamp. */
  updatedAt: string;
}

/** A time slot where the user is unavailable. */
export interface BlockedSlot {
  /** Unique identifier. */
  id: string;
  /** Optional display label. */
  title?: string;
  /** Type of block. */
  blockType: BlockType;
  /** ISO-8601 start date (or date-time for single-day). */
  startDate: string;
  /** ISO-8601 end date (required for recurring-period). */
  endDate?: string;
  /** Start time in HH:mm format (recurring-weekday). */
  startTime?: string;
  /** End time in HH:mm format (recurring-weekday). */
  endTime?: string;
  /** Days of week (0=Sun, 1=Mon, …, 6=Sat) for recurring-weekday. */
  daysOfWeek?: number[];
  /** Whether the block repeats. */
  isRecurring: boolean;
}

/** User settings. */
export interface Settings {
  /** Hour the work day starts (0–23). */
  workStartHour: number;
  /** Hour the work day ends (0–23). */
  workEndHour: number;
  /** Days of week that are work days (0=Sun, …, 6=Sat). */
  workDays: number[];
  /** Maximum number of tasks per day. */
  maxTasksPerDay: number;
  /** Default duration for new tasks in minutes. */
  defaultTaskDuration: number;
  /** IANA timezone identifier. */
  timezone: string;
  /** Whether shuffle mode is enabled. */
  shuffleEnabled: boolean;
  /** Week start day (0=Sun, 1=Mon). */
  weekStartDay: number;
}

/** A calendar event (normalised from Google Calendar or system-generated). */
export interface CalendarEvent {
  /** Google Calendar event ID. */
  id: string;
  /** Event title. */
  title: string;
  /** ISO-8601 start date-time. */
  start: string;
  /** ISO-8601 end date-time. */
  end: string;
  /** Whether the event spans the entire day. */
  isAllDay: boolean;
  /** Whether the event was generated by BrkRoutnXdle. */
  isGenerated: boolean;
  /** If generated, the originating task ID. */
  taskId?: string;
  /** Whether the event has been completed. */
  isCompleted: boolean;
  /** Source calendar. */
  source: "google" | "brkroutnxdle";
  /** Whether this event represents a blocked time slot. */
  isBlock?: boolean;
}

/** Authenticated user information. */
export interface User {
  /** Google account ID. */
  id: string;
  /** Email address. */
  email: string;
  /** Display name. */
  name: string;
  /** Avatar URL. */
  picture?: string;
}

/** Generic API response envelope. */
export interface ApiResponse<T = unknown> {
  /** Whether the request succeeded. */
  success: boolean;
  /** Response payload on success. */
  data?: T;
  /** Error details on failure. */
  error?: ApiError;
}

/** Structured API error. */
export interface ApiError {
  /** Machine-readable error code. */
  code: string;
  /** Human-readable error message. */
  message: string;
  /** Additional error context. */
  details?: unknown;
}
